#!/usr/bin/env python3
"""One-off converter: Flare (.flr, JSON v21) -> sprite atlases + Dart data.

The exercise faces were sprite animations inside Flare files: a base64 PNG
atlas, a few image quads and linear/hold keys on posX/posY/opacity. This
script wrote assets/anim/*.png and lib/src/anim/face_sprites.g.dart from them
so the app could drop the abandoned flare_flutter package. Kept for
provenance; the .flr sources are gone from the repo.
"""
import base64, json, struct, sys

FILES = {
    'lrtbFaceFast': 'lrtbFace',
    'blinkingFast': 'blinking',
    'screwUpFast': 'screwUp',
    'farSeingFast': 'farSeeing',
    'palmingFast': 'palming',
}

def png_size(b):
    assert b[:8] == b'\x89PNG\r\n\x1a\n'
    return struct.unpack('>II', b[16:24])

def d(v):
    """Dart double literal that round-trips the JSON value exactly."""
    return repr(float(v))

out = ["// GENERATED by tool/flare_to_sprites.py from the original Flare files.",
       "// Do not edit by hand.",
       "",
       "import 'dart:ui';",
       "",
       "import 'package:eyehelper/src/anim/sprite_sheet.dart';",
       ""]

for src, ident in FILES.items():
    doc = json.load(open(f'assets/{src}.flr'))
    ab = doc['artboards'][0]
    atlas_b64 = doc['atlases']['data'][0].split(',', 1)[1]
    atlas = base64.b64decode(atlas_b64)
    aw, ah = png_size(atlas)
    asset = f'assets/anim/{ident}.png'
    open(asset, 'wb').write(atlas)

    nodes = ab['nodes']
    # Layers keep their original indexes so animation tracks line up; hidden
    # or unsupported nodes become null-free placeholders by being skipped in
    # a remap table.
    remap = {}
    layers = []
    for i, n in enumerate(nodes):
        t = n['type']
        if t == 'image':
            if not n.get('isVisible', True) or 'vertices' not in n:
                continue
            v = n['vertices']
            xs, ys, us, vs = v[0::4], v[1::4], v[2::4], v[3::4]
            # The quad must map local extents to uv extents without a flip.
            imin = min(range(4), key=lambda k: (xs[k], ys[k]))
            assert us[imin] == min(us) and vs[imin] == min(vs), f'{src}: flipped quad on {n["name"]}'
            remap[i] = len(layers)
            layers.append(dict(
                kind='image', name=n['name'], parent=n.get('parent'),
                tx=n['translation'][0], ty=n['translation'][1], scale=n['scale'][0],
                opacity=n['opacity'], draw=n['drawOrder'],
                src=(min(us) * aw, min(vs) * ah, max(us) * aw, max(vs) * ah),
                local=(min(xs), min(ys), max(xs), max(ys)),
            ))
        elif t == 'shape':
            # A shape is a container: its fill and its path are children.
            fill = next(c for c in nodes if c.get('parent') == i and c['type'] == 'colorFill')
            path = next(c for c in nodes if c.get('parent') == i and c['type'] == 'rectangle')
            r, g, b, a = fill['color']
            remap[i] = len(layers)
            layers.append(dict(
                kind='rect', name=n['name'], parent=n.get('parent'),
                tx=n['translation'][0] + path['translation'][0],
                ty=n['translation'][1] + path['translation'][1],
                scale=n['scale'][0], opacity=n['opacity'], draw=n['drawOrder'],
                w=path['width'], h=path['height'],
                color=(round(a * 255), round(r * 255), round(g * 255), round(b * 255)),
            ))
    for l in layers:
        if l['parent'] is not None:
            l['parent'] = remap[l['parent']]

    out.append(f"/// {src}.flr — atlas {aw}x{ah}, artboard {ab['width']}x{ab['height']}.")
    out.append(f"const SpriteSheet {ident}Sprites = SpriteSheet(")
    out.append(f"  atlas: '{asset}',")
    out.append(f"  artboard: Size({d(ab['width'])}, {d(ab['height'])}),")
    out.append("  layers: [")
    for idx, l in enumerate(layers):
        parent = 'null' if l['parent'] is None else str(l['parent'])
        out.append(f"    // {idx}: {l['name']}")
        if l['kind'] == 'image':
            out.append("    SpriteImageLayer(")
            out.append(f"      parent: {parent},")
            out.append(f"      translation: Offset({d(l['tx'])}, {d(l['ty'])}),")
            out.append(f"      scale: {d(l['scale'])},")
            out.append(f"      opacity: {d(l['opacity'])},")
            out.append(f"      drawOrder: {l['draw']},")
            out.append(f"      src: Rect.fromLTRB({', '.join(d(x) for x in l['src'])}),")
            out.append(f"      local: Rect.fromLTRB({', '.join(d(x) for x in l['local'])}),")
            out.append("    ),")
        else:
            a, r, g, b = l['color']
            out.append("    SpriteRectLayer(")
            out.append(f"      parent: {parent},")
            out.append(f"      translation: Offset({d(l['tx'])}, {d(l['ty'])}),")
            out.append(f"      scale: {d(l['scale'])},")
            out.append(f"      opacity: {d(l['opacity'])},")
            out.append(f"      drawOrder: {l['draw']},")
            out.append(f"      size: Size({d(l['w'])}, {d(l['h'])}),")
            out.append(f"      color: Color(0x{a:02X}{r:02X}{g:02X}{b:02X}),")
            out.append("    ),")
    out.append("  ],")
    out.append("  animations: [")
    for anim in ab['animations']:
        out.append(f"    SpriteAnimation('{anim['name']}', {d(anim['duration'])}, [")
        for k in anim.get('keyed', []):
            comp = k['component']
            if comp not in remap:
                continue  # keys on a hidden node
            for prop, groups in k.items():
                if prop == 'component':
                    continue
                keys = [x for grp in groups for x in (grp if isinstance(grp, list) else [grp])]
                keys.sort(key=lambda x: x['time'])
                out.append(f"      SpriteTrack({remap[comp]}, SpriteProp.{prop}, [")
                for key in keys:
                    it = key.get('interpolatorType', 1)
                    assert it in (0, 1), f'{src}: unsupported interpolator {it}'
                    hold = ', hold: true' if it == 0 else ''
                    out.append(f"        SpriteKey({d(key['time'])}, {d(key['value'])}{hold}),")
                out.append("      ]),")
        out.append("    ]),")
    out.append("  ],")
    out.append(");")
    out.append("")

open('lib/src/anim/face_sprites.g.dart', 'w').write('\n'.join(out))
print('wrote lib/src/anim/face_sprites.g.dart and', len(FILES), 'atlases')
